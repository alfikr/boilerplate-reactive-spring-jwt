-- Initial schema. login/email are stored lower-cased by the application; the unique
-- constraints are the real guard against concurrent duplicate registrations.

CREATE TABLE authority (
    name varchar(50) PRIMARY KEY
);

INSERT INTO authority (name) VALUES ('ROLE_ADMIN'), ('ROLE_USER');

CREATE TABLE users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login               varchar(50)  NOT NULL,
    password            varchar(60)  NOT NULL,
    first_name          varchar(50),
    last_name           varchar(50),
    email               varchar(254) NOT NULL,
    aktif               boolean      NOT NULL DEFAULT false,
    activation_key_hash char(64),
    reset_key_hash      char(64),
    reset_date          timestamptz,
    ins_on              timestamptz  NOT NULL,
    create_by           varchar(50)  NOT NULL,
    mod_on              timestamptz,
    mod_by              varchar(50),
    CONSTRAINT ux_users_login UNIQUE (login),
    CONSTRAINT ux_users_email UNIQUE (email)
);

-- One-time keys are looked up by hash; partial indexes stay small (most rows are NULL).
CREATE UNIQUE INDEX ux_users_activation_key ON users (activation_key_hash) WHERE activation_key_hash IS NOT NULL;
CREATE UNIQUE INDEX ux_users_reset_key ON users (reset_key_hash) WHERE reset_key_hash IS NOT NULL;

CREATE TABLE user_authority (
    user_id        bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    authority_name varchar(50) NOT NULL REFERENCES authority (name),
    PRIMARY KEY (user_id, authority_name)
);

-- Execution log written by AspectConfiguration. Grows with traffic: add partitioning or a
-- scheduled purge (DELETE ... WHERE event_date < ...) matching your retention policy.
CREATE TABLE jvs_audit (
    event_id        bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    principal       varchar(100) NOT NULL,
    event_date      timestamptz  NOT NULL,
    log_type        varchar(20),
    title           varchar(100),
    class_name      varchar(255),
    method_name     varchar(100),
    execution_start bigint,
    execution_end   bigint,
    execution_time  bigint,
    error           boolean      NOT NULL,
    error_message   text,
    message         text
);

CREATE INDEX ix_jvs_audit_event_date ON jvs_audit (event_date);
